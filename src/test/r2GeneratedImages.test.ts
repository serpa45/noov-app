// @vitest-environment node
import { afterEach, expect, it, vi } from "vitest";
import { uploadGeneratedImageToR2 } from "../../supabase/functions/_shared/r2Images";
afterEach(() => vi.unstubAllGlobals());
const options = { origin: "https://noov.app.br", serviceRoleKey: "private-server-credential", bucket: "banners" as const, path: "materiais/a.png", bytes: new Uint8Array([1]), contentType: "image/png" };
it("sends server-generated bytes only to the approved internal endpoint", async () => {
  const upstream = vi.fn<typeof fetch>(async () => new Response(JSON.stringify({ publicUrl: "https://noov.app.br/media/banners/materiais/a.png" })));
  vi.stubGlobal("fetch", upstream);
  expect(await uploadGeneratedImageToR2(options)).toContain("/media/banners/");
  expect(upstream.mock.calls[0][0]).toBe("https://noov.app.br/api/media-internal/banners/materiais/a.png");
});
it("does not forward server credentials to arbitrary destinations", async () => {
  const upstream = vi.fn(); vi.stubGlobal("fetch", upstream);
  await expect(uploadGeneratedImageToR2({ ...options, origin: "https://untrusted.test" })).rejects.toThrow("não autorizado");
  expect(upstream).not.toHaveBeenCalled();
});
it("does not report success on a rejected upload", async () => {
  vi.stubGlobal("fetch", vi.fn(async () => new Response("{}", { status: 503 })));
  await expect(uploadGeneratedImageToR2(options)).rejects.toThrow("HTTP 503");
});
